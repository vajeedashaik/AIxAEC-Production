// Converts packages/contracts/schema/bundle.json into apps/web/src/contracts/generated.ts and copies the
// JSON fixtures into apps/web/src/mocks/fixtures/ (the web build can't import outside apps/web).
// Run from apps/web: `npm run gen:contracts` (after `uv run python scripts/export_schema.py` here).
// `--check` exits 1 if anything is out of date (for CI).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "../../../apps/web");
const require = createRequire(resolve(web, "package.json"));
const { compile } = require("json-schema-to-typescript");

const bundle = JSON.parse(readFileSync(resolve(here, "../schema/bundle.json"), "utf8"));
const defs = bundle.$defs;

// Pydantic puts a `title` on every property; json-schema-to-typescript would turn each into a named type.
// Keep titles only on definitions, named after the def key ("FloorPlanModel-Output" -> FloorPlanModelOutput).
function stripTitles(node) {
  if (Array.isArray(node)) return node.map(stripTitles);
  if (node && typeof node === "object") {
    // {$ref, default} would become a fresh duplicate type (Source1, Source2...); a bare ref reuses the def.
    if ("$ref" in node) return { $ref: node.$ref };
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "title") continue;
      // keys under `properties` are field names (a field may be called "title"), not schema keywords
      out[k] = k === "properties" ? Object.fromEntries(Object.entries(v).map(([f, s]) => [f, stripTitles(s)])) : stripTitles(v);
    }
    return out;
  }
  return node;
}
for (const [key, def] of Object.entries(defs)) {
  defs[key] = { ...stripTitles(def), title: key.replace(/-/g, "") };
}

const ts = await compile({ $defs: defs, type: "object", additionalProperties: false }, "_Root", {
  bannerComment:
    "// GENERATED by packages/contracts/scripts/gen_ts.mjs from packages/contracts/schema/bundle.json.\n// DO NOT EDIT. Frozen contracts: see phases/shared/CONTRACTS.md §12 for change requests.",
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { semi: true, singleQuote: false, printWidth: 110 },
});
const body = ts.replace(/export interface _Root \{\}\n?/, "");

const fixtures = resolve(here, "../fixtures");
const mockDir = resolve(web, "src/mocks/fixtures");
const outputs = new Map([[resolve(web, "src/contracts/generated.ts"), body]]);
for (const name of readdirSync(fixtures).filter((f) => f.endsWith(".model.json")))
  outputs.set(resolve(mockDir, name), readFileSync(resolve(fixtures, name), "utf8"));
for (const name of readdirSync(resolve(fixtures, "api")).filter((f) => f.endsWith(".json")))
  outputs.set(resolve(mockDir, "api", name), readFileSync(resolve(fixtures, "api", name), "utf8"));

if (process.argv.includes("--check")) {
  const stale = [...outputs].filter(([path, content]) => {
    try {
      return readFileSync(path, "utf8") !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error("Out of date (run `npm run gen:contracts`):\n" + stale.map(([p]) => "  " + p).join("\n"));
    process.exit(1);
  }
  console.log("generated contracts and mock fixtures are up to date");
} else {
  mkdirSync(resolve(mockDir, "api"), { recursive: true });
  for (const [path, content] of outputs) writeFileSync(path, content);
  console.log(`wrote ${outputs.size} files`);
}
